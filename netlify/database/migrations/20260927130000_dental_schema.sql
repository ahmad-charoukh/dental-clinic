CREATE TABLE patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    phone VARCHAR(60) NOT NULL,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL,
    title_ar VARCHAR(200) NOT NULL,
    title_tr VARCHAR(200) NOT NULL,
    title_en VARCHAR(200) NOT NULL,
    description_ar TEXT NOT NULL,
    description_tr TEXT NOT NULL,
    description_en TEXT NOT NULL,
    image VARCHAR(300) NOT NULL,
    duration INTEGER NOT NULL,
    sessions INTEGER NOT NULL,
    price DOUBLE PRECISION,
    sort_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id),
    service_id INTEGER NOT NULL REFERENCES services(id),
    starts_at TIMESTAMP NOT NULL,
    slot_key VARCHAR(32),
    status VARCHAR(32) NOT NULL,
    notes TEXT NOT NULL,
    locale VARCHAR(5) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE articles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(160) NOT NULL UNIQUE,
    title_ar VARCHAR(240) NOT NULL,
    title_tr VARCHAR(240) NOT NULL,
    title_en VARCHAR(240) NOT NULL,
    body_ar TEXT NOT NULL,
    body_tr TEXT NOT NULL,
    body_en TEXT NOT NULL,
    published BOOLEAN NOT NULL
);

CREATE TABLE audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(255) NOT NULL,
    action VARCHAR(120) NOT NULL,
    entity VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80) NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE blocked_dates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day DATE NOT NULL,
    reason VARCHAR(200) NOT NULL
);

CREATE TABLE clinical_cases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    treatment_type VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    before_image VARCHAR(300) NOT NULL,
    after_image VARCHAR(300) NOT NULL,
    status VARCHAR(20) NOT NULL,
    case_date DATE
);

CREATE TABLE clinical_notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id),
    note TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE email_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL,
    provider_id VARCHAR(120) NOT NULL,
    error TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE faq (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_ar VARCHAR(300) NOT NULL,
    question_tr VARCHAR(300) NOT NULL,
    question_en VARCHAR(300) NOT NULL,
    answer_ar TEXT NOT NULL,
    answer_tr TEXT NOT NULL,
    answer_en TEXT NOT NULL,
    sort_order INTEGER NOT NULL,
    published BOOLEAN NOT NULL
);

CREATE TABLE media (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(255) NOT NULL,
    path VARCHAR(300) NOT NULL,
    mime VARCHAR(100) NOT NULL,
    category VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(60) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    body_ar TEXT NOT NULL,
    body_tr TEXT NOT NULL,
    body_en TEXT NOT NULL,
    rating INTEGER NOT NULL,
    published BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE site_settings (
    "key" VARCHAR(100) PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE treatment_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id),
    title VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    notes TEXT NOT NULL
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE working_hours (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekday INTEGER NOT NULL UNIQUE,
    enabled BOOLEAN NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    break_start TIME,
    break_end TIME
);
